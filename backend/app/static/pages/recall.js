// Recall page (/app/recall/) -- interactive recall as a *session*, not a
// single request/response.
//
// The user starts from a vague cue; the backend
// (app/retrieval/session.py) runs a bounded round, and then either
// answers, asks exactly one discriminating question
// (app/retrieval/discriminate.py + infogain.py), or explicitly declines.
// Every reply the user sends is just another cue, so answering the
// question, ignoring it in favour of a different detail, and correcting
// an earlier turn all go through the same endpoint.
//
// What this file is responsible for, beyond rendering:
//
//   * Never letting an inferred lead look like a match. A candidate
//     whose `route` is "association" is labelled and styled as a lead
//     reached by inference, and its confidence is rendered with the
//     shared `.confidence` meter so the *length* of the fill carries the
//     signal, not colour alone. The backend goes to real lengths to keep
//     that distinction (app/retrieval/associative.py's score ceiling,
//     evidence.py's confidence cap, the answer prompt's explicit note);
//     the UI must not undo it.
//   * Never inventing wording for confidence. CONFIDENCE_DESCRIPTIONS
//     below is a verbatim copy of app/retrieval/evidence.py's table.
//   * Never presenting a system hypothesis as a fact -- hypotheses are
//     rendered with `.prov-hypothesis`, the vocabulary app.css defines
//     for exactly that.
//   * Treating `exhausted` as an explanation, not an error: the session
//     deliberately declined, and `abstention_reason` says why.
//
// Everything user-supplied goes through escapeHtml before it reaches
// innerHTML (see core.js's note on that), same discipline as
// pages/library.js. Per-page state lives in the initRecallPage closure.
(() => {
  "use strict";

  const {
    hide,
    show,
    showStatus,
    escapeHtml,
    postJSON,
    fetchWithTimeout,
    formatElapsed,
    describeError,
    buildAttachmentList,
  } = window.membase;

  // ------------------------------------------------------------------
  // Vocabulary. Every string in this section mirrors the backend's own
  // wording -- see app/retrieval/evidence.py. Nothing here is invented
  // phrasing for a concept the backend already names.
  // ------------------------------------------------------------------

  // Verbatim from evidence.py's CONFIDENCE_DESCRIPTIONS.
  const CONFIDENCE_DESCRIPTIONS = {
    strong:
      "This memory matched your query directly and strongly, with no stored " +
      "memory contradicting it.",
    moderate:
      "This memory matched your query, but either not decisively or with " +
      "some supporting evidence coming from inferred associations rather " +
      "than from the memory's own words.",
    weak:
      "This memory was reached mainly through associations with other " +
      "memories, or it matched only weakly. Treat it as a lead, not an " +
      "answer.",
    insufficient:
      "There is not enough evidence to put this memory forward as the " +
      "answer.",
  };

  const CONFIDENCE_LABELS = {
    strong: "Strong",
    moderate: "Moderate",
    weak: "Weak",
    insufficient: "Not enough evidence",
  };

  // The four levels app.css's `.prov-*` vocabulary is built around. The
  // badge carries a short form (it sits inline beside a sentence, and
  // `.provenance` is uppercase + letter-spaced, so a full phrase there
  // would dominate the sentence it qualifies); evidence.py's own
  // provenance_label() wording is kept verbatim as the tooltip, so the
  // long form is never lost and never paraphrased.
  const PROVENANCE_LABELS = {
    original: "your words",
    extracted: "extracted",
    inferred: "inferred",
    hypothesis: "guess",
  };

  // Verbatim from evidence.py's provenance_label().
  const PROVENANCE_DESCRIPTIONS = {
    original: "your own words",
    extracted: "extracted from your words",
    inferred: "inferred by the system",
    hypothesis: "a search guess, not a fact",
  };

  // evidence.py's ROUTE_* constants, said in full.
  const ROUTE_LABELS = {
    direct: "Matched your query directly",
    both: "Matched directly, and is also connected to another match",
    association: "Lead reached by inference -- not a match",
  };

  // evidence.py's KIND_* constants. The detail sentence beside each item
  // is generated by the backend; this is only a short tag for the kind.
  const KIND_LABELS = {
    direct_match: "direct match",
    lexical_match: "shared wording",
    association: "association",
    shared_entity: "shared entity",
    cue_match: "your cue",
    cue_conflict: "cue conflict",
    contradiction: "contradiction",
    sibling: "same note",
    attachment: "attachment",
    degraded_semantics: "incomplete analysis",
    temporal: "date",
    hypothesis: "search guess",
  };

  // session.py's status set.
  const STATUS_META = {
    active: { label: "searching", cls: "badge-accent" },
    needs_user_cue: { label: "needs one more detail", cls: "badge-accent" },
    success: { label: "answered", cls: "badge-success" },
    exhausted: { label: "declined to answer", cls: "badge-warning" },
    cancelled: { label: "stopped", cls: "badge-neutral" },
    error: { label: "error", cls: "badge-danger" },
  };

  const TERMINAL_STATUSES = ["success", "exhausted", "cancelled", "error"];

  // ------------------------------------------------------------------
  // Small rendering helpers
  // ------------------------------------------------------------------

  function confidenceCategory(raw) {
    return Object.prototype.hasOwnProperty.call(CONFIDENCE_LABELS, raw) ? raw : "insufficient";
  }

  // The `.confidence` primitive from app.css: a three-segment meter whose
  // fill length is the signal. "insufficient" is deliberately an empty
  // dashed track, not a short bar.
  function confidenceMeter(raw) {
    const cat = confidenceCategory(raw);
    return (
      `<span class="confidence conf-${cat}" title="${escapeHtml(CONFIDENCE_DESCRIPTIONS[cat])}">` +
      `${escapeHtml(CONFIDENCE_LABELS[cat])}</span>`
    );
  }

  function provenanceBadge(level) {
    const known = Object.prototype.hasOwnProperty.call(PROVENANCE_LABELS, level) ? level : "inferred";
    return (
      `<span class="provenance prov-${known}" title="${escapeHtml(PROVENANCE_DESCRIPTIONS[known])}">` +
      `${escapeHtml(PROVENANCE_LABELS[known])}</span>`
    );
  }

  function pill(text, title, strong) {
    const cls = strong ? "pill pill-strong" : "pill";
    const titleAttr = title ? ` title="${escapeHtml(title)}"` : "";
    return `<span class="${cls}"${titleAttr}>${escapeHtml(text)}</span>`;
  }

  function badge(text, variantClass) {
    return `<span class="badge ${variantClass}">${escapeHtml(text)}</span>`;
  }

  function score(value) {
    return typeof value === "number" ? value.toFixed(2) : "n/a";
  }

  // Memory ids are UUIDs: shown truncated with the full value in a
  // tooltip, so a narrow viewport never has to scroll sideways to get
  // past one.
  function shortId(id) {
    const text = String(id || "");
    return pill(text.slice(0, 8), `Memory ${text}`);
  }

  function storedOn(iso) {
    if (!iso) return "";
    const date = new Date(iso);
    return Number.isNaN(date.getTime()) ? "" : date.toLocaleDateString();
  }

  // ------------------------------------------------------------------
  // The page
  // ------------------------------------------------------------------

  function initRecallPage() {
    const askForm = document.getElementById("recall-form");
    const queryInput = document.getElementById("query");
    const submitButton = document.getElementById("recall-submit");
    const newButton = document.getElementById("recall-new");
    const statusEl = document.getElementById("status");

    const sessionEl = document.getElementById("session");
    const sessionQueryEl = document.getElementById("session-query");
    const sessionMetaEl = document.getElementById("session-meta");
    const sessionNoteEl = document.getElementById("session-note");
    const cancelButton = document.getElementById("session-cancel");

    const transcriptEl = document.getElementById("transcript");
    const replyBlock = document.getElementById("reply-block");
    const questionEl = document.getElementById("current-question");
    const replyForm = document.getElementById("reply-form");
    const replyInput = document.getElementById("reply-text");
    const replySubmit = document.getElementById("reply-submit");
    const replyStatus = document.getElementById("reply-status");

    const candidatesWrap = document.getElementById("candidates-wrap");
    const candidatesEl = document.getElementById("candidates");
    const candidatesNote = document.getElementById("candidates-note");
    const chunksWrap = document.getElementById("chunks-wrap");
    const chunksEl = document.getElementById("chunks");
    const cuesWrap = document.getElementById("cues-wrap");
    const cuesEl = document.getElementById("cues");
    const hypothesesWrap = document.getElementById("hypotheses-wrap");
    const hypothesesEl = document.getElementById("hypotheses");
    const trailEl = document.getElementById("trail");
    const trailBody = document.getElementById("trail-body");

    // Per-page state, in this closure only (the pattern pages/store.js
    // and pages/library.js use).
    let session = null;
    let inFlight = false;
    // Incremented by every request start AND by a cancel, so a reply that
    // is still in flight when the user stops the session cannot land and
    // overwrite the cancelled state with its own (now stale) result.
    let generation = 0;

    function isTerminal(status) {
      return TERMINAL_STATUSES.indexOf(status) !== -1;
    }

    function setInFlight(busy) {
      inFlight = busy;
      submitButton.disabled = busy;
      replySubmit.disabled = busy;
      submitButton.textContent = busy ? "Recalling..." : session ? "Start a new recall" : "Start recalling";
    }

    // The shared spinner/status pattern (core.js's showStatus) plus a
    // live elapsed counter: a round against the local model takes tens of
    // seconds, and silence for that long is indistinguishable from a
    // frozen page.
    async function withElapsed(target, label, work) {
      const startedAt = performance.now();
      showStatus(target, `${label}...`);
      const ticker = setInterval(() => {
        showStatus(target, `${label}... (${formatElapsed(performance.now() - startedAt)} elapsed)`);
      }, 200);
      try {
        const result = await work();
        clearInterval(ticker);
        hide(target);
        return result;
      } catch (err) {
        clearInterval(ticker);
        showStatus(target, describeError(err, performance.now() - startedAt), true);
        throw err;
      }
    }

    // ----------------------------------------------------------------
    // Requests
    // ----------------------------------------------------------------

    async function startSession(query) {
      const gen = ++generation;
      setInFlight(true);
      hide(replyStatus);
      try {
        const data = await withElapsed(statusEl, "Searching your memories", () =>
          postJSON("/api/recall/sessions", { query })
        );
        if (gen !== generation) return;
        session = data;
        render();
      } catch {
        // withElapsed already reported it into #status.
      } finally {
        if (gen === generation) setInFlight(false);
      }
    }

    async function sendReply(text) {
      if (!session) return;
      const gen = ++generation;
      setInFlight(true);
      try {
        const data = await withElapsed(replyStatus, "Searching again with that", () =>
          postJSON(`/api/recall/sessions/${session.id}/messages`, { text })
        );
        if (gen !== generation) return;
        session = data;
        replyInput.value = "";
        render();
      } catch {
        // Reported into #reply-status; the session is untouched and the
        // user can edit their reply and try again.
      } finally {
        if (gen === generation) setInFlight(false);
      }
    }

    async function cancelSession() {
      if (!session) return;
      // Bumping the generation first is what makes an in-flight round's
      // response land harmlessly instead of resurrecting the session.
      const gen = ++generation;
      cancelButton.disabled = true;
      try {
        const data = await withElapsed(statusEl, "Stopping", () =>
          postJSON(`/api/recall/sessions/${session.id}/cancel`, {})
        );
        if (gen !== generation) return;
        session = data;
        render();
      } catch {
        // Reported into #status.
      } finally {
        cancelButton.disabled = false;
        if (gen === generation) setInFlight(false);
      }
    }

    // ----------------------------------------------------------------
    // Render: head
    // ----------------------------------------------------------------

    function renderHead() {
      sessionQueryEl.textContent = session.original_query;

      const meta = STATUS_META[session.status] || { label: session.status, cls: "badge-neutral" };
      const parts = [badge(meta.label, meta.cls)];
      if (session.confidence) {
        // Populated while a question is still pending too (see
        // app/retrieval/session.py's _ask), where it describes the leading
        // candidate rather than an answer -- so it must not be labelled as
        // confidence in an answer that does not exist yet.
        // Only a session that actually produced an answer has confidence
        // *in an answer*; every other status that carries a confidence
        // (a pending question, a cancelled or exhausted session) is
        // describing the leading candidate so far.
        const answered = session.status === "success";
        parts.push(
          `<span class="recall-meta-confidence">${confidenceMeter(session.confidence)}</span>`,
          pill(
            answered ? "confidence in the answer" : "confidence so far",
            answered
              ? ""
              : "How well-supported the leading candidate is at this point -- no answer has been given"
          )
        );
      }
      parts.push(pill(`round ${session.round_count}`, "Rounds of user-mediated search so far", true));
      parts.push(
        pill(
          `${session.last_candidate_count} candidate${session.last_candidate_count === 1 ? "" : "s"} last round`,
          "How many memories (and matching document excerpts) the last round considered",
          true
        )
      );
      sessionMetaEl.innerHTML = parts.join(" ");

      let note = "";
      if (session.status === "needs_user_cue") {
        note =
          `${session.last_candidate_count} stored ` +
          `${session.last_candidate_count === 1 ? "memory is" : "memories are"} still plausible, so rather ` +
          "than guess, it asked one question below. The candidates it is choosing between, and the " +
          "evidence for each, are shown further down -- you are not being asked about memories you " +
          "cannot see.";
      } else if (session.status === "cancelled") {
        note = "You stopped this session. Its cues and trail are kept below; start a new recall above to search again.";
      } else if (session.status === "error") {
        note = "The backend hit an error while searching. Nothing was written to your stored memories -- try again.";
      } else if (session.status === "active") {
        note = "A round is still running.";
      }
      sessionNoteEl.textContent = note;
      if (note) show(sessionNoteEl);
      else hide(sessionNoteEl);

      if (isTerminal(session.status)) hide(cancelButton);
      else show(cancelButton);
    }

    // ----------------------------------------------------------------
    // Render: transcript
    // ----------------------------------------------------------------

    function renderTranscript() {
      const all = session.messages || [];
      // The question still awaiting an answer is rendered by the reply
      // block immediately below, where it belongs with the field that
      // answers it. Leaving it in the transcript too would print the same
      // sentence twice, a few lines apart. Once answered it reappears here
      // in its proper place in the record (the reply block is gone by
      // then), so nothing is lost.
      const pendingQuestionTrails =
        session.status === "needs_user_cue" &&
        session.current_question &&
        all.length > 0 &&
        all[all.length - 1].role === "system" &&
        all[all.length - 1].text === session.current_question;
      const messages = pendingQuestionTrails ? all.slice(0, -1) : all;
      transcriptEl.innerHTML = "";

      messages.forEach((message, index) => {
        const isUser = message.role === "user";
        const isLast = index === messages.length - 1;
        const li = document.createElement("li");
        li.className = `recall-turn recall-turn-${isUser ? "user" : "system"}`;

        let eyebrow = isUser ? "You" : "membase";
        let textClass = "recall-turn-text";
        if (!isUser && isLast && session.status === "success") {
          eyebrow = "Answer";
          textClass = "recall-turn-text answer";
        } else if (!isUser && isLast && session.status === "exhausted") {
          eyebrow = "No answer given";
          textClass = "recall-turn-text answer abstained";
        } else if (!isUser && isLast && session.status === "needs_user_cue") {
          eyebrow = "membase asks";
        }

        // `data-turn` rather than the text in an attribute: save-as-memory
        // must send back exactly what the user said, byte for byte (the
        // server matches it against the session's own user-supplied text),
        // and an attribute round-trip is a needless place to lose a
        // newline.
        li.innerHTML =
          `<p class="eyebrow">${escapeHtml(eyebrow)}</p>` +
          `<p class="${textClass}">${escapeHtml(message.text)}</p>` +
          (isUser
            ? `<div class="row recall-turn-actions">
                 <button type="button" class="btn-link recall-save" data-turn="${index}">Save this as a memory</button>
                 <span class="recall-save-status muted hidden"></span>
               </div>`
            : "");

        // Abstention is an explanation, not an error: the system decided
        // it could not honestly answer, and said why.
        if (!isUser && isLast && session.status === "exhausted" && session.abstention_reason) {
          const reason = document.createElement("p");
          reason.className = "caption recall-abstention";
          reason.textContent = `Why: ${session.abstention_reason}`;
          li.appendChild(reason);
        }

        transcriptEl.appendChild(li);
      });

      // Save-as-memory, offered on the user's own turns only -- the server
      // rejects anything else, and a system question or hypothesis is not
      // the user's memory to store (see api/recall.py's save_as_memory).
      for (const button of transcriptEl.querySelectorAll(".recall-save")) {
        const turnIndex = Number(button.dataset.turn);
        const statusSpan = button.parentElement.querySelector(".recall-save-status");
        button.addEventListener("click", async () => {
          const text = (session.messages[turnIndex] || {}).text;
          if (!text) return;
          button.disabled = true;
          statusSpan.className = "recall-save-status muted";
          statusSpan.textContent = "Saving...";
          try {
            await postJSON(`/api/recall/sessions/${session.id}/save-as-memory`, { text });
            statusSpan.textContent = "Saved as a new memory -- it is being processed in the background (see Library).";
            button.remove();
          } catch (err) {
            statusSpan.className = "recall-save-status error";
            statusSpan.textContent = err.message;
            button.disabled = false;
          }
        });
      }

      if (session.status === "needs_user_cue" && session.current_question) {
        questionEl.textContent = session.current_question;
        show(replyBlock);
      } else {
        hide(replyBlock);
      }
    }

    // ----------------------------------------------------------------
    // Render: candidates and their evidence
    // ----------------------------------------------------------------

    function evidenceGroup(title, items, extraClass) {
      if (!items.length) return "";
      const rows = items
        .map(
          (item) => `
          <li class="recall-evidence-item">
            <div class="row row-tight recall-evidence-tags">
              ${provenanceBadge(item.provenance)}
              ${pill(KIND_LABELS[item.kind] || item.kind)}
            </div>
            <p class="recall-evidence-detail">${escapeHtml(item.detail)}</p>
          </li>`
        )
        .join("");
      return `
        <div class="recall-evidence-group ${extraClass}">
          <p class="eyebrow">${escapeHtml(title)} (${items.length})</p>
          <ul class="recall-evidence-list">${rows}</ul>
        </div>`;
    }

    function candidateCard(candidate, sourceById) {
      const isLead = candidate.route === "association";
      const routeLabel = ROUTE_LABELS[candidate.route] || candidate.route;
      const items = candidate.evidence || [];
      const supporting = items.filter((e) => e.polarity === "supporting");
      const contradicting = items.filter((e) => e.polarity === "contradicting");
      const neutral = items.filter((e) => e.polarity !== "supporting" && e.polarity !== "contradicting");
      const cat = confidenceCategory(candidate.confidence);

      // An association-route candidate is visually and textually a lead,
      // never a result. This is a correctness requirement, not styling:
      // the backend caps its score and confidence precisely so an
      // inferred lead cannot be read as a finding.
      const leadBanner = isLead
        ? `<p class="recall-lead-banner">
             ${provenanceBadge("inferred")}
             <span>This memory did not match what you asked. It was reached by inference
             ${candidate.association_hops ? `(${escapeHtml(String(candidate.association_hops))} hop${candidate.association_hops === 1 ? "" : "s"})` : ""}
             from a memory that did. Treat it as a lead to follow, not an answer.</span>
           </p>`
        : "";

      const meaning = candidate.meaning
        ? `<p class="caption recall-candidate-meaning">${escapeHtml(candidate.meaning)}</p>`
        : "";

      const why = candidate.association_why
        ? `<p class="caption recall-candidate-why">${escapeHtml(candidate.association_why)}</p>`
        : "";

      // `event_date` is whatever the enrichment step recorded, and that is
      // not always a date -- observed live on the demo corpus: "Not
      // specified in the primary memory (though related memories suggest a
      // timeframe between 2021 and 2023)". So it gets a wrapping line of
      // its own rather than a `.pill`, which is `white-space: nowrap` by
      // design and would push the page sideways on a narrow viewport.
      const recordedDate = candidate.event_date
        ? `<p class="caption recall-candidate-date">Recorded date: ${escapeHtml(candidate.event_date)}</p>`
        : "";

      const facts = [
        shortId(candidate.unit_id),
        pill(`match ${score(candidate.base_score)}`, "Retrieval relevance, before any evidence adjustment"),
        pill(`rank ${score(candidate.score)}`, "Score after re-ranking on contextual consistency and evidence quality"),
      ];
      if (typeof candidate.association_strength === "number") {
        facts.push(pill(`link strength ${score(candidate.association_strength)}`, "Decayed association strength through the memory graph"));
      }
      const stored = storedOn(candidate.created_at);
      if (stored) facts.push(pill(`stored ${stored}`));

      const card = document.createElement("article");
      card.className = `card recall-candidate${isLead ? " recall-candidate-lead" : ""}`;
      card.innerHTML = `
        ${leadBanner}
        <div class="card-head">
          <p class="recall-candidate-route">${escapeHtml(routeLabel)}</p>
          ${confidenceMeter(candidate.confidence)}
        </div>
        <p class="recall-candidate-content">${escapeHtml(candidate.content)}</p>
        ${meaning}
        ${why}
        ${recordedDate}
        <p class="caption recall-confidence-note">${escapeHtml(CONFIDENCE_DESCRIPTIONS[cat])}</p>
        <div class="row row-tight recall-candidate-facts">${facts.join(" ")}</div>
        <p class="recall-attachments muted hidden"></p>
        <div class="recall-evidence">
          ${evidenceGroup("Supporting", supporting, "recall-evidence-supporting")}
          ${evidenceGroup("Contradicting", contradicting, "recall-evidence-contradicting")}
          ${evidenceGroup("Noted", neutral, "recall-evidence-neutral")}
        </div>
        <div class="row recall-candidate-actions">
          <button type="button" class="btn btn-secondary btn-sm recall-assoc" data-hops="1">Connected memories (1 hop)</button>
          <button type="button" class="btn btn-secondary btn-sm recall-assoc" data-hops="2">Widen to 2 hops</button>
          <button type="button" class="btn btn-secondary btn-sm recall-episodes">Episodes it belongs to</button>
        </div>
        <div class="recall-network hidden"></div>
        <p class="recall-network-status status hidden"></p>
      `;

      // The retrieved memory's own original files, opened through
      // core.js's openAttachment (the only path that carries the
      // Authorization header this backend needs).
      const source = sourceById[candidate.unit_id];
      if (source && source.attachments && source.attachments.length) {
        const attachmentsEl = card.querySelector(".recall-attachments");
        attachmentsEl.appendChild(buildAttachmentList(source.attachments));
        show(attachmentsEl);
      }

      wireNetworkButtons(card, candidate.unit_id);
      return card;
    }

    // Navigation from a retrieved answer into the memory network behind
    // it: GET /api/graph/units/{id}/associations (each result carrying a
    // deterministic `why`) and GET /api/episodes/for-unit/{id}.
    function wireNetworkButtons(card, unitId) {
      const networkEl = card.querySelector(".recall-network");
      const networkStatus = card.querySelector(".recall-network-status");

      async function load(label, path, renderInto) {
        hide(networkEl);
        showStatus(networkStatus, `${label}...`);
        try {
          const resp = await fetchWithTimeout(path);
          const data = await resp.json().catch(() => []);
          if (!resp.ok) throw new Error(data.detail || `Failed to load (${resp.status})`);
          hide(networkStatus);
          networkEl.innerHTML = renderInto(data);
          show(networkEl);
        } catch (err) {
          showStatus(networkStatus, err.message, true);
        }
      }

      for (const button of card.querySelectorAll(".recall-assoc")) {
        const hops = button.dataset.hops;
        button.addEventListener("click", () =>
          load(
            `Walking the memory graph (${hops} hop${hops === "1" ? "" : "s"})`,
            `/api/graph/units/${unitId}/associations?hops=${hops}`,
            (associated) => renderAssociations(associated, hops)
          )
        );
      }

      card.querySelector(".recall-episodes").addEventListener("click", () =>
        load("Loading episodes", `/api/episodes/for-unit/${unitId}`, renderEpisodes)
      );
    }

    function renderAssociations(associated, hops) {
      if (!associated.length) {
        return `<p class="empty-state">Nothing is connected to this memory within ${escapeHtml(String(hops))} hop${hops === "1" ? "" : "s"}.</p>`;
      }
      const rows = associated
        .map((a) => {
          const path = a.path || [];
          // For a one-hop neighbour the whole-path `why` IS that hop's own
          // explanation, so listing both just prints the same sentence
          // twice. The step list only earns its space when the path is
          // genuinely multi-step.
          const showPath = path.length > 1;
          const steps = showPath
            ? path
                .map(
                  (step) =>
                    `<li class="recall-path-step">${escapeHtml(step.explanation || `${step.kind} (${step.origin})`)}</li>`
                )
                .join("")
            : "";
          return `
            <li class="recall-assoc-item">
              <div class="row row-tight">
                ${provenanceBadge("inferred")}
                ${pill(`${a.hops} hop${a.hops === 1 ? "" : "s"}`)}
                ${pill(`strength ${score(a.strength)}`)}
              </div>
              <p class="recall-assoc-content">${escapeHtml(a.unit.authoritative_content)}</p>
              <p class="caption recall-assoc-why">${escapeHtml(a.why)}</p>
              ${steps ? `<p class="eyebrow recall-path-label">Step by step</p><ul class="recall-path">${steps}</ul>` : ""}
            </li>`;
        })
        .join("");
      return `
        <p class="eyebrow">Connected memories</p>
        <p class="muted">
          These are connections the system computed, not statements you made. The
          reason given for each one is deterministic -- it is the actual path
          through the graph, not a generated explanation.
        </p>
        <ul class="recall-assoc-list">${rows}</ul>`;
    }

    function renderEpisodes(episodes) {
      if (!episodes.length) {
        return `<p class="empty-state">This memory is not part of any episode.</p>`;
      }
      const rows = episodes
        .map(
          (e) => `
          <li class="recall-episode-item">
            <p class="recall-episode-title">${escapeHtml(e.title)}</p>
            <div class="row row-tight">
              ${pill(e.date_display)}
              ${pill(`${e.member_count} memor${e.member_count === 1 ? "y" : "ies"}`)}
              ${pill(`span ${e.boundary_confidence}`, "Whether the episode's span is the user's own claim, derived from extraction, or genuinely open")}
              ${pill(`title ${e.title_source}`)}
            </div>
            ${e.summary ? `<p class="caption">${escapeHtml(e.summary)}</p>` : ""}
            ${e.anchors && e.anchors.length ? `<p class="muted">About: ${escapeHtml(e.anchors.join(", "))}</p>` : ""}
          </li>`
        )
        .join("");
      return `<p class="eyebrow">Episodes</p><ul class="recall-episode-list">${rows}</ul>`;
    }

    function renderCandidates() {
      const candidates = session.evidence || [];
      candidatesEl.innerHTML = "";
      if (!candidates.length) {
        hide(candidatesWrap);
        return;
      }
      const sourceById = {};
      for (const source of session.sources || []) sourceById[source.id] = source;

      const leads = candidates.filter((c) => c.route === "association").length;
      // While a question is pending these are the memories the question is
      // choosing between, not the basis of an answer -- the backend
      // snapshots them for exactly that reason (app/retrieval/session.py's
      // _ask), and saying "considered" there would misdescribe them.
      const pending = session.status === "needs_user_cue";
      candidatesNote.textContent =
        (pending
          ? `These are the ${candidates.length} memor${candidates.length === 1 ? "y" : "ies"} the question above is choosing between`
          : `${candidates.length} candidate${candidates.length === 1 ? " was" : "s were"} considered`) +
        (leads
          ? `, of which ${leads} ${leads === 1 ? "is a lead reached" : "are leads reached"} by inference rather than a match.`
          : candidates.length === 1
            ? ", reached by matching your query rather than by inference."
            : ", all of them reached by matching your query rather than by inference.") +
        " The memory text below is stored data, not generated;" +
        (pending
          ? " nothing here has been put forward as an answer yet."
          : " only the answer in the session above is written by a model.");

      for (const candidate of candidates) candidatesEl.appendChild(candidateCard(candidate, sourceById));
      show(candidatesWrap);
    }

    function renderChunks() {
      const chunks = session.chunk_sources || [];
      chunksEl.innerHTML = "";
      if (!chunks.length) {
        hide(chunksWrap);
        return;
      }
      chunksEl.innerHTML = chunks
        .map(
          (c) => `
          <li class="source-item">
            <strong class="source-summary">${escapeHtml(c.attachment_filename)}</strong>
            ${c.page_number !== null && c.page_number !== undefined ? pill(`page ${c.page_number}`) : ""}
            ${pill(`match ${score(c.fused_score)}`)}
            <span class="caption source-quote">&ldquo;${escapeHtml(c.excerpt)}&rdquo;</span>
          </li>`
        )
        .join("");
      show(chunksWrap);
    }

    // ----------------------------------------------------------------
    // Render: cues and hypotheses
    // ----------------------------------------------------------------

    function renderCues() {
      const cues = session.cues || [];
      cuesEl.innerHTML = "";
      if (!cues.length) {
        hide(cuesWrap);
        return;
      }
      cuesEl.innerHTML = cues
        .map((cue) => {
          const positive = cue.polarity === "positive";
          return `
            <li class="recall-cue">
              <div class="row row-tight">
                ${badge(positive ? "include" : "rule out", positive ? "badge-success" : "badge-danger")}
                ${pill(`stated as ${cue.confidence}`, "How firmly you stated this: certain, likely, or uncertain", true)}
                ${pill(`round ${cue.round}`)}
              </div>
              <p class="recall-cue-text">${escapeHtml(cue.text)}</p>
            </li>`;
        })
        .join("");
      show(cuesWrap);
    }

    function renderHypotheses() {
      const hypotheses = session.hypotheses || [];
      hypothesesEl.innerHTML = "";
      if (!hypotheses.length) {
        hide(hypothesesWrap);
        return;
      }
      hypothesesEl.innerHTML = hypotheses
        .map(
          (h) => `
          <li class="recall-hypothesis">
            ${provenanceBadge("hypothesis")}
            <span class="recall-hypothesis-text">${escapeHtml(h.text)}</span>
            ${pill(`round ${h.round}`)}
          </li>`
        )
        .join("");
      show(hypothesesWrap);
    }

    // ----------------------------------------------------------------
    // Render: the retrieval trail
    // ----------------------------------------------------------------

    // The question block is where the trail earns its keep: it says which
    // attribute was asked about and what the selector thought it was worth.
    //
    // Two numbers, not one. `expected_gain_bits_approx` is the raw mutual
    // information between a truthful answer and candidate identity;
    // `utility_approx` is that discounted by `answerability` -- how reliably a
    // person can answer a question about this kind of attribute at all -- and
    // utility is what the question was actually ranked by (see
    // app/retrieval/infogain.py's FIELD_ANSWERABILITY). Both are shown,
    // because a question that won on answerability rather than on raw split
    // should be visible as such.
    function renderQuestionBlock(question) {
      if (!question) return "";
      const separates = question.separates || {};
      const yes = (separates.yes || []).length;
      const no = (separates.no || []).length;
      const num = (value) => (typeof value === "number" ? value : null);
      const gain = num(question.expected_gain_bits_approx);
      const utility = num(question.utility_approx);
      const answerability = num(question.answerability);
      const before = num(question.entropy_before_bits_approx);

      // Which of the two drove the choice. They only coincide when the
      // attribute is fully answerable; a discount means the ranking was not
      // the raw split's ranking.
      let driver = "";
      if (answerability !== null && gain !== null && utility !== null) {
        driver =
          answerability >= 1
            ? "Raw gain and utility agree here: this attribute is one you can answer " +
              "outright, so nothing was discounted and the best split was also the " +
              "best question."
            : "Chosen by utility, not by raw gain: this attribute is only " +
              `${escapeHtml(answerability.toFixed(2))} as answerable as a concrete name or place, ` +
              "so its raw gain was discounted before ranking. A split that looks ideal " +
              "on paper is worth little if you cannot actually confirm or deny it.";
      }

      return `
        <div class="recall-round-question">
          <p class="eyebrow">The question it chose, and why</p>
          <p class="recall-round-question-text">${escapeHtml(question.question || "")}</p>
          <dl class="recall-kv">
            <dt>Attribute asked about</dt>
            <dd>${escapeHtml(question.field || "unknown")}${question.value ? ` = &ldquo;${escapeHtml(question.value)}&rdquo;` : ""}</dd>
            ${
              utility === null
                ? ""
                : `<dt>Utility it was ranked by (approximate)</dt>
                   <dd>~${escapeHtml(utility.toFixed(2))} bits
                     <span class="muted">
                       Expected gain multiplied by answerability. Approximate on purpose: an
                       ordering signal for choosing between possible questions, not a
                       measurement of anything.
                     </span>
                   </dd>`
            }
            ${
              gain === null
                ? ""
                : `<dt>Raw expected information gain (approximate)</dt>
                   <dd>~${escapeHtml(gain.toFixed(2))} bits
                     <span class="muted">
                       What a truthful answer would be worth if this attribute were perfectly
                       answerable. Also approximate -- the candidate distribution behind it
                       comes from retrieval scores, which rank but do not calibrate.
                     </span>
                   </dd>`
            }
            ${
              answerability === null
                ? ""
                : `<dt>Answerability of this attribute</dt>
                   <dd>${escapeHtml(answerability.toFixed(2))}
                     <span class="muted">
                       How reliably a person can answer a question about this kind of
                       attribute: a name or a place, yes; a thematic label the extraction
                       model invented, much less so.
                     </span>
                   </dd>`
            }
            ${
              before === null
                ? ""
                : `<dt>Uncertainty before asking (approximate)</dt>
                   <dd>~${escapeHtml(before.toFixed(2))} bits</dd>`
            }
            <dt>What it separates</dt>
            <dd>${escapeHtml(String(yes))} candidate group${yes === 1 ? "" : "s"} would answer yes, ${escapeHtml(String(no))} would answer no.</dd>
          </dl>
          ${driver ? `<p class="caption recall-question-driver">${driver}</p>` : ""}
        </div>`;
    }

    function renderTrail() {
      const trail = session.strategy_trail || [];
      trailBody.innerHTML = "";
      if (!trail.length) {
        hide(trailEl);
        return;
      }
      trailBody.innerHTML = trail
        .map((entry) => {
          const strategies = (entry.strategies || []).map((s) => pill(s.replace(/_/g, " "))).join(" ");
          const ruledOut = (entry.ruled_out || [])
            .map(
              (r) => `
              <li class="recall-ruled-out-item">
                <p class="recall-ruled-out-content">${escapeHtml(r.content)}</p>
                <p class="caption">${escapeHtml(r.reason)}</p>
              </li>`
            )
            .join("");
          const hypotheses = (entry.hypotheses || [])
            .map((h) => `<li>${provenanceBadge("hypothesis")} <span>${escapeHtml(h)}</span></li>`)
            .join("");
          const budget = entry.budget || {};
          const budgetBits = Object.keys(budget)
            .map((key) => pill(`${key.replace(/_/g, " ")} ${budget[key]}`))
            .join(" ");

          return `
            <section class="card card-quiet recall-round">
              <div class="card-head">
                <h3>Round ${escapeHtml(String(entry.round))}</h3>
                ${typeof entry.elapsed_ms === "number" ? pill(formatElapsed(entry.elapsed_ms), "Wall-clock time this round took") : ""}
              </div>
              <p class="eyebrow">Strategies run</p>
              <div class="row row-tight">${strategies || pill("none recorded")}</div>
              <div class="row row-tight recall-round-counts">
                ${pill(`${entry.direct_candidates || 0} matched directly`, "Candidates that cleared the retrieval bar on their own", true)}
                ${pill(`${entry.expanded_candidates || 0} reached by association`, "Candidates found by walking the memory graph from a direct match", true)}
              </div>
              ${
                entry.expansion_skipped_reason
                  ? `<p class="caption recall-skipped">Association exploration was skipped deliberately: ${escapeHtml(entry.expansion_skipped_reason)}.</p>`
                  : ""
              }
              ${
                ruledOut
                  ? `<div class="recall-ruled-out">
                       <p class="eyebrow">Ruled out by your own cues</p>
                       <ul class="recall-ruled-out-list">${ruledOut}</ul>
                     </div>`
                  : ""
              }
              ${
                hypotheses
                  ? `<div class="recall-round-hypotheses">
                       <p class="eyebrow">Reformulations it tried this round</p>
                       <ul class="recall-hypothesis-list">${hypotheses}</ul>
                     </div>`
                  : ""
              }
              ${renderQuestionBlock(entry.question)}
              ${budgetBits ? `<p class="eyebrow">Budget in force</p><div class="row row-tight">${budgetBits}</div>` : ""}
            </section>`;
        })
        .join("");
      show(trailEl);
    }

    // ----------------------------------------------------------------

    function render() {
      renderHead();
      renderTranscript();
      renderCandidates();
      renderChunks();
      renderCues();
      renderHypotheses();
      renderTrail();
      show(sessionEl);
      show(newButton);
      submitButton.textContent = "Start a new recall";
      if (session.status === "needs_user_cue") replyInput.focus();
    }

    function resetSession() {
      generation += 1;
      session = null;
      hide(sessionEl);
      hide(newButton);
      hide(statusEl);
      hide(replyStatus);
      transcriptEl.innerHTML = "";
      candidatesEl.innerHTML = "";
      trailEl.open = false;
      queryInput.value = "";
      replyInput.value = "";
      setInFlight(false);
      submitButton.textContent = "Start recalling";
      queryInput.focus();
    }

    // ----------------------------------------------------------------
    // Wiring
    // ----------------------------------------------------------------

    askForm.addEventListener("submit", (ev) => {
      ev.preventDefault();
      if (inFlight) return;
      const query = queryInput.value.trim();
      if (!query) return;
      // A second submit starts a genuinely new session rather than
      // continuing the old one -- continuing is what the reply box is
      // for. The old session's rendering is cleared first so there is
      // never a moment where last session's evidence sits under this
      // session's spinner.
      session = null;
      hide(sessionEl);
      // Collapsed by default is per session, not just per page load: the
      // trail belongs to the search that produced it, so a new search
      // starts with the audit view folded away again.
      trailEl.open = false;
      startSession(query);
    });

    replyForm.addEventListener("submit", (ev) => {
      ev.preventDefault();
      if (inFlight) return;
      const text = replyInput.value.trim();
      if (!text) return;
      sendReply(text);
    });

    cancelButton.addEventListener("click", cancelSession);
    newButton.addEventListener("click", resetSession);
  }

  window.membase.initRecallPage = initRecallPage;
})();
